const dictionaries: Record<Locale, Record<MessageKey, string>> = { 'pt-BR': ptBR, en };

export function normalizeLocale(value: unknown): Locale | undefined {
  if (typeof value !== 'string') return undefined;
  const lower = value.trim().toLowerCase();
  if (lower === 'en' || lower.startsWith('en-') || lower.startsWith('en_')) return 'en';
  if (lower === 'pt' || lower.startsWith('pt-') || lower.startsWith('pt_')) return 'pt-BR';
  return undefined;
}

export function translator(locale: Locale) {
  return (key: MessageKey, vars: Record<string, string | number> = {}) => dictionaries[locale][key].replace(/\{(\w+)\}/g, (match, name: string) => name in vars ? String(vars[name]) : match);
}

let current: Locale = DEFAULT_LOCALE;
export function setLocale(locale: Locale) { current = locale; }
export function getLocale() { return current; }
export function t(key: MessageKey, vars?: Record<string, string | number>) { return translator(current)(key, vars); }
